A = 5   # В двоичном виде: 101
B = 3   # В двоичном виде: 011
C = 6   # В двоичном виде: 110

print("КОМПЬЮТЕРНЫЙ ЭКСПЕРИМЕНТ С ПОБИТОВЫМИ ОПЕРАЦИЯМИ")
print(f"Число A: {A} (в битах: {bin(A)[2:]:>3})")
print(f"Число B: {B} (в битах: {bin(B)[2:]:>3})")
print(f"Число C: {C} (в битах: {bin(C)[2:]:>3})\n")

# Чтобы побитовое НЕ (~) работало корректно для 3-битных чисел, используем маску & 7
# 1. Выражение: ¬(A ∧ B) ∨ ¬(A ∨ C)
expr1 = (~(A & B) & 7) | (~(A | C) & 7)

# 2. Выражение: (A ∧ B) ∨ (¬B ∧ C)
expr2 = (A & B) | ((~B & 7) & C)

# 3. Выражение со скриншота: (A ∧ B) ∨ ¬C
expr3 = (A & B) | (~C & 7)

print("-" * 55)
print(f"Результат выражения 1: {expr1} (в битах: {bin(expr1)[2:]:>3})")
print(f"Результат выражения 2: {expr2} (в битах: {bin(expr2)[2:]:>3})")
print(f"Результат выражения 3: {expr3} (в битах: {bin(expr3)[2:]:>3})")
print("-" * 55)
